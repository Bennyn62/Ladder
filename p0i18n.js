const K_LANG = 'ladder.lang';
let UI_LANG = 'he';
const T_MISS = {};

function T(s, ...a){
  let v;
  if(UI_LANG === 'en'){
    v = EN_UI[s];
    if(v === undefined){ T_MISS[s] = (T_MISS[s]||0)+1; v = s; }
  } else v = s;
  return a.length ? String(v).replace(/\{(\d+)\}/g, (m,i)=> a[i] ?? '') : v;
}
T.missing = ()=> Object.keys(T_MISS).sort();

/* החלת השפה: כיוון, שפה, ומחלקה ל-CSS ייעודי.
   כל ה-CSS כתוב בתכונות לוגיות, ולכן ההיפוך עובד בלי כללים כפולים. */
function applyLang(){
  const u = (typeof me === 'function') ? me() : null;
  UI_LANG = (u && u.settings && u.settings.lang)
    ? u.settings.lang
    : (localStorage.getItem(K_LANG) || 'he');
  try{ localStorage.setItem(K_LANG, UI_LANG); }catch(e){}
  const html = document.documentElement;
  html.setAttribute('lang', UI_LANG === 'en' ? 'en' : 'he');
  html.setAttribute('dir',  UI_LANG === 'en' ? 'ltr' : 'rtl');
  html.dataset.uilang = UI_LANG;
}

